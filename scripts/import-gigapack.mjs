import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve } from 'node:path';

// The supplied JSON is the content source. Only its obsolete root is remapped.
const specPath = process.argv[2] ?? 'docs/monsterbonk_gigapack_relics_11_20_spec.json';
const count = Number(process.argv[3] ?? 10);
const spec = JSON.parse(readFileSync(specPath, 'utf8'));
const root = 'assets/pixel/effects/Super Pixel Effects Gigapack (Free Version)/';
const clips = {};
for (const relic of spec.relics.slice(0, count)) for (const clip of relic.vfx) {
  const url = root + clip.spritesheet.replace(/^effects\//, '');
  const metadata = root + clip.metadata.replace(/^effects\//, '');
  const png = readFileSync(resolve('public', url));
  const width = png.readUInt32BE(16), height = png.readUInt32BE(20);
  const frames = readFileSync(resolve('public', metadata), 'utf8').trim().split(/\r?\n/).map(line => {
    const m = line.match(/frame(\d+)\.png\s*=\s*(\d+)\s+(\d+)\s+(\d+)\s+(\d+)\s*$/);
    if (!m) throw new Error(`Invalid Gigapack metadata: ${line}`);
    const [index,x,y,w,h] = m.slice(1).map(Number);
    if (w <= 0 || h <= 0 || x+w > width || y+h > height) throw new Error(`Out-of-bounds frame: ${line}`);
    return { index, rect:[x,y,w,h] };
  }).sort((a,b)=>a.index-b.index);
  if (!frames.length || frames.some((f,i)=>f.index!==i)) throw new Error(`Noncontiguous animation: ${clip.clip}`);
  clips[clip.clip] = { url, metadata, width, height, frames:frames.map(f=>f.rect), fps:15 };
}
mkdirSync('src/visuals', {recursive:true});
writeFileSync('src/visuals/gigapack-clips.ts', '// Generated by scripts/import-gigapack.mjs from real spritesheet.txt rectangles. FPS: pack guide.txt.\nexport const GIGAPACK_CLIPS = '+JSON.stringify(clips,null,2)+' as const;\nexport type GigapackClipId = keyof typeof GIGAPACK_CLIPS;\n');
console.log(`Parsed ${Object.keys(clips).length} actual Gigapack spritesheets`);
