"""Normalize visible card subjects offline; preserve original artwork and gameplay assets."""
import json
import math
from pathlib import Path
import subprocess
import tempfile
from PIL import Image

ROOT=Path(__file__).resolve().parents[1]
UI=ROOT/'public/assets/ui'
OUT=UI/'card-art'
SIZE=256
# Existing presentation trims excluded adjacent icons; bake these into the derivative.
LEFT_TRIMS={'upgrade/illustrations/skills/returning-ring.png':.20,'upgrade/illustrations/skills/ice-radiance.png':.10}

def quantile(weights,fraction):
    target=sum(weights)*fraction
    total=0
    for index,value in enumerate(weights):
        total+=value
        if total>=target:return index
    return len(weights)-1

def normalize(image):
    image=image.convert('RGBA')
    # Strong-alpha mass ignores faint scattered glow and dust when locating the subject.
    thumb=image.copy();thumb.thumbnail((512,512),Image.Resampling.LANCZOS)
    width,height=thumb.size
    columns=[0.0]*width;rows=[0.0]*height
    for index,alpha in enumerate(thumb.getchannel('A').getdata()):
        weight=(alpha/255)**2 if alpha>=48 else 0
        columns[index%width]+=weight;rows[index//width]+=weight
    mass=sum(columns)
    if mass==0:raise ValueError('Empty or fully faint card artwork')
    left,right=quantile(columns,.005),quantile(columns,.995)+1
    top,bottom=quantile(rows,.005),quantile(rows,.995)+1
    sx,sy=image.width/width,image.height/height
    box=[left*sx,top*sy,right*sx,bottom*sy]
    bw,bh=box[2]-box[0],box[3]-box[1]
    # Optical area helps airy/slender subjects; the longest edge prevents clipping cores.
    scale=min(224/max(bw,bh),math.sqrt(20000/(mass*sx*sy)))
    resized=image.resize((max(1,round(image.width*scale)),max(1,round(image.height*scale))),Image.Resampling.LANCZOS)
    result=Image.new('RGBA',(SIZE,SIZE))
    result.alpha_composite(resized,(round(SIZE/2-(box[0]+box[2])/2*scale),round(SIZE/2-(box[1]+box[3])/2*scale)))
    return result,{'core':list(map(lambda n:round(n,2),box)),'coreSize':[round(bw*scale,2),round(bh*scale,2)],'scale':round(scale,5)}

def main():
    sources=sorted(p for p in (UI/'upgrade/illustrations').rglob('*') if p.suffix in ('.png','.svg'))
    sources.append(UI/'shop/health-potion.png')
    mapping={};records=[];images={}
    with tempfile.TemporaryDirectory(prefix='monsterbonk-card-art-') as temp:
        temp=Path(temp);jobs=[]
        for i,source in enumerate(sources):
            if source.suffix=='.svg':jobs.append({'source':str(source),'output':str(temp/f'{i}.png')})
        if jobs:
            jobfile=temp/'jobs.json';jobfile.write_text(json.dumps(jobs),encoding='utf-8')
            subprocess.run(['node',str(ROOT/'scripts/rasterize-card-svg.mjs'),str(jobfile)],cwd=ROOT,check=True)
        for i,source in enumerate(sources):
            key=source.relative_to(UI).as_posix()
            image=Image.open(temp/f'{i}.png' if source.suffix=='.svg' else source).convert('RGBA')
            if key in LEFT_TRIMS:image=image.crop((round(image.width*LEFT_TRIMS[key]),0,image.width,image.height))
            result,metrics=normalize(image)
            filename=Path(key).with_suffix('.webp') if source.suffix=='.png' else Path(key).with_name(source.stem+'-vector.webp')
            relative=Path('card-art')/filename
            output=UI/relative;output.parent.mkdir(parents=True,exist_ok=True)
            result.save(output,'WEBP',quality=86,method=6)
            mapping[key]=relative.as_posix();images[key]=result
            records.append({'source':key,'output':relative.as_posix(),'sourceBytes':source.stat().st_size,'bytes':output.stat().st_size,**metrics})
    combinations=[('split-elements',['split-on-hit-fire','split-on-hit-thorn']),('chain-elements',['chain-bounce-water','chain-bounce-grass']),('boiling-core',['area-expansion','split-on-hit-fire'])]
    combined={}
    for name,names in combinations:
        keys=[f'upgrade/illustrations/skills/{n}.png' for n in names]
        canvas=Image.new('RGBA',(320,320))
        for i,key in enumerate(keys):canvas.alpha_composite(images[key].resize((224,224),Image.Resampling.LANCZOS),(i*96,(1-i)*70))
        result,_=normalize(canvas);output=OUT/f'{name}.webp';result.save(output,'WEBP',quality=86,method=6)
        combined['|'.join(keys)]=f'card-art/{name}.webp'
    code='// Generated by scripts/prepare-card-art.py. Original sources are retained.\n'
    code+='export const CARD_ART:Readonly<Record<string,string>>='+json.dumps(mapping,ensure_ascii=False,indent=2)+';\n'
    code+='export const COMBINED_CARD_ART:Readonly<Record<string,string>>='+json.dumps(combined,ensure_ascii=False,indent=2)+';\n'
    (ROOT/'src/card-art-manifest.ts').write_text(code,encoding='utf-8')
    report=ROOT/'artifacts/card-art';report.mkdir(parents=True,exist_ok=True)
    (report/'manifest.json').write_text(json.dumps(records,ensure_ascii=False,indent=2),encoding='utf-8')
    # One contact sheet for human review, never loaded by the game.
    sheet=Image.new('RGB',(1024,math.ceil(len(images)/8)*148),'#ded8c8')
    from PIL import ImageDraw
    draw=ImageDraw.Draw(sheet)
    for i,(key,image) in enumerate(images.items()):
        x=(i%8)*128;y=(i//8)*148;sheet.paste(image.resize((128,128)),(x,y),image.resize((128,128)))
        draw.text((x+2,y+128),Path(key).stem[:20],fill='#25372d')
    sheet.save(report/'contact-sheet.jpg',quality=90)
    before=sum(r['sourceBytes'] for r in records);after=sum(r['bytes'] for r in records)+sum((UI/p).stat().st_size for p in combined.values())
    print(f'Prepared {len(records)} icons + {len(combined)} combined icons: {before:,} -> {after:,} bytes ({(1-after/before)*100:.1f}% smaller).')

if __name__=='__main__':main()
